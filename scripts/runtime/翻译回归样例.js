function evaluateTranslations(localizer, samples) {
  const outputs = samples.translationProbeTargets.map(input => ({ input, output: localizer.translate(input) }));
  return {
    untranslated: outputs.filter(item => item.output === item.input).map(item => item.input),
    englishHits: outputs.map(item => {
      const hits = samples.residualEnglish.filter(needle => String(item.output || "").includes(needle));
      return hits.length ? { ...item, hits } : null;
    }).filter(Boolean),
    unexpectedTranslations: samples.translationProbeExpectations.map(([input, expected]) => {
      const output = localizer.translate(input);
      return output === expected ? null : { input, expected, output };
    }).filter(Boolean),
    preservationFailures: samples.translationPreservationTargets.map(input => {
      const output = localizer.translate(input);
      return output === input ? null : { input, output };
    }).filter(Boolean)
  };
}

